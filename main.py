@app.get("/pack")
def pack_form():
    return pack_page()


@app.post("/pack")
def pack_submit():
    email = (request.form.get("email") or "").strip().lower()
    if not EMAIL.match(email) or len(email) > 254:
        return pack_page("That does not look like an email address.", "bad", email), 400
    if not os.path.exists(PACK):
        return pack_page("The pack is being rebuilt — try again in a moment.", "bad", email), 503

    os.makedirs(DATA, exist_ok=True)
    with open(LEADS, "a", encoding="utf-8") as fh:
        fh.write(json.dumps({
            "email": email,
            "at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
            "referer": (request.headers.get("Referer") or "")[:300],
        }) + "\n")
    print(f"[lead] {email}", flush=True)

    return send_file(PACK, as_attachment=True,
                     download_name="frontline-hiring-pack.zip",
                     mimetype="application/zip")


