"""
Serves the Claude Skills for HR Ops library.

One process does three jobs:
  - serves the per-skill pages generated by site/build.py
  - hands out the real installable .zip for each skill
  - gates the full pack behind an email

On boot it builds anything missing, so a fresh clone runs with no setup.

    python3 main.py            # http://localhost:8080
    BUILD=always python3 main.py   # rebuild pages and packages first
"""

