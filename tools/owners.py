"""
Skill ownership. owners.json is the one place it is written down; this script
turns it into .github/CODEOWNERS, which is what makes GitHub request the owner's
review on every pull request that touches their skill.

    python3 tools/owners.py            # regenerate .github/CODEOWNERS
    python3 tools/owners.py --check    # CI: fail if anything is out of line
    python3 tools/owners.py --who      # print who owns what

Ownership rotates, so handing a skill over is a one-line edit to owners.json
(change "owner", update "since"), then a regenerate, in the same commit.

What --check refuses:
  - a skill on disk with no owner        -> every skill has someone answering for it
  - an owner who is not in "people"      -> a typo would silently orphan a skill
  - a CODEOWNERS that does not match     -> it is generated, never edited by hand
A slug in owners.json with no folder on this branch is only a warning: owners
are assigned before the skill's pull request is merged.

A person whose "github" is null has no account yet; their skills are routed to
the fallback so a review is still requested from someone. Fill in the username
once they have one -- and give them write access to the repository, or GitHub
ignores the line.
"""

import glob, json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)
SOURCE = "owners.json"
TARGET = ".github/CODEOWNERS"


def skills_on_disk():
    found = {}
    for path in glob.glob("skills/*/*/SKILL.md"):
        found[os.path.basename(os.path.dirname(path))] = path
    for path in glob.glob("skills/*/*.md"):
        found[os.path.basename(path)[:-3]] = path
    return found


def load():
    return json.load(open(SOURCE, encoding="utf-8"))


def handle(data, person_id):
    gh = data["people"][person_id].get("github")
    if gh:
        return "@" + gh
    return "@" + data["people"][data["fallback"]]["github"]


def render(data):
    people = data["people"]
    lines = [
        "# GENERATED by tools/owners.py from owners.json -- do not edit by hand.",
        "# To change an owner: edit owners.json, run python3 tools/owners.py, commit both.",
        "",
        "# Everything without a more specific owner.",
        f"* {handle(data, data['fallback'])}",
        "",
    ]
    for slug in sorted(data["skills"]):
        entry = data["skills"][slug]
        person = people[entry["owner"]]
        note = f"# {slug}: {person['name']} (since {entry['since']})"
        if not person.get("github"):
            note += " -- no GitHub account yet, routed to the fallback"
        lines += [note, f"/skills/*/{slug}/ {handle(data, entry['owner'])}", ""]
    return "\n".join(lines)


def problems(data):
    fail, warn = [], []
    people = data.get("people", {})
    if data.get("fallback") not in people or not people[data["fallback"]].get("github"):
        fail.append("fallback must be a person with a GitHub username")
    for slug, entry in data.get("skills", {}).items():
        if entry.get("owner") not in people:
            fail.append(f"{slug}: owner '{entry.get('owner')}' is not in people")
        if not entry.get("since"):
            fail.append(f"{slug}: missing 'since'")
    for pid, person in people.items():
        photo = person.get("photo")
        if photo and not os.path.exists(photo):
            fail.append(f"{pid}: photo {photo} does not exist")
    disk = skills_on_disk()
    for slug, path in sorted(disk.items()):
        if slug not in data.get("skills", {}):
            fail.append(f"{path}: no owner in {SOURCE}")
    for slug in sorted(set(data.get("skills", {})) - set(disk)):
        warn.append(f"{slug}: owned but not on this branch (fine if its PR is pending)")
    return fail, warn


def main(argv):
    data = load()
    fail, warn = problems(data)
    if "--who" in argv:
        for slug in sorted(data["skills"]):
            e = data["skills"][slug]
            p = data["people"].get(e["owner"], {"name": e["owner"]})
            print(f"{slug:32} {p['name']:24} since {e['since']}")
        return 0
    if not fail:
        expected = render(data)
        if "--check" in argv:
            current = open(TARGET, encoding="utf-8").read() if os.path.exists(TARGET) else ""
            if current != expected:
                fail.append(f"{TARGET} is out of date: run python3 tools/owners.py")
        else:
            os.makedirs(os.path.dirname(TARGET), exist_ok=True)
            open(TARGET, "w", encoding="utf-8").write(expected)
            print(f"wrote {TARGET}")
    for w in warn:
        print("WARN  " + w)
    for f in fail:
        print("FAIL  " + f)
    if fail:
        return 1
    print("Owners check passed.")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
